def _regen_format_for_brand(ctx, archetype: str) -> str | None:
    """First format id for `archetype` that the active brand actually owns
    (ctx.formats membership), or None if it owns none -- the caller falls
    back to the single-clip pixel-remix path in that case rather than
    forcing a mismatched/off-niche format (see this module's docstring)."""
    for fmt in _ARCHETYPE_FORMATS.get(archetype, []):
        if fmt in ctx.formats:
            return fmt
    return None


def _extract_preview_frames(video_path: str, n: int = 3) -> list[Path]:
    """Same pattern as white_card_reaction._extract_preview_frames /
    upload_meta._grab_frame -- a handful of evenly-sampled, downscaled JPEGs
    fed to Claude as @path references (the CLI's own vision syntax).

    2026-08-14, real reliability bug caught live: originally 6 (rather than
    format18's 3) specifically so ranking/listicle structure -- which only
    shows up across several distinct segments -- wouldn't get missed by a
    too-small sample landing inside a single item. Reverted back to
    format18's 3 after live testing showed the CLI's own vision attachment
    is NOT 100% reliable per-image to begin with (modules.claude_cli's
    _maybe_reground_vision_call, added the same day, retries once when the
    whole call looks ungrounded) -- 6 separate attachments in one call gives
    that failure far more surface area (any one of six silently skipped is
    enough to misread the source), while 3 is the number this pipeline
    already has actual production experience trusting. Ranking detection
    from 3 frames is a known, accepted tradeoff versus outright misreading
    the clip's content -- not chasing it further tonight."""
    dur = _duration_ffprobe(video_path)
    _TMP_DIR.mkdir(parents=True, exist_ok=True)
    for f in _TMP_DIR.glob("*.jpg"):
        f.unlink(missing_ok=True)
    frames = []
    for i in range(n):
        t = dur * (i + 0.5) / n
        out = _TMP_DIR / f"frame_{i}.jpg"
        cmd = ["ffmpeg", "-y", "-ss", f"{t:.2f}", "-i", video_path, "-frames:v", "1",
               "-vf", "scale=480:-2", "-q:v", "4", str(out)]
        r = subprocess.run(cmd, capture_output=True)
        if r.returncode == 0 and out.exists():
            frames.append(out)
    return frames


def _transcribe_source(video_path: str) -> str:
    """Whisper transcript of the source clip's own audio (modules.clips.
    clip_transcriber, the same local Whisper call format6/mf1's own
    generation branches already use) -- several archetypes (dialogue,
    hotline, audit) have little to no distinctive VISUAL signature and are
    only obvious once you can read what's actually being said; frames alone
    badly under-detect them. Returns "" (not an error) on no speech/no
    audio/any transcription failure -- classification still runs on frames
    alone in that case, same as before this was added."""
    try:
        if not _has_audio(video_path):
            return ""
        from modules.clips.clip_transcriber import transcribe_clip
        text = transcribe_clip(Path(video_path)).get("full_text", "").strip()
        if text:
            logger.info(f"viral_remix: transcribed {len(text)} chars from source audio")
        return text
    except Exception as e:
        logger.warning(f"viral_remix: transcription failed ({e}), classifying from frames alone")
        return ""


