"""
"Remix a viral video" -- a new Publication-panel input source (2026-08-13,
explicit user ask): take a clip that already buzzed elsewhere (a link the
user pastes, or a file they downloaded by hand) and hand back a version
transformed just enough to dodge reused-content detection on TikTok/IG/FB/
Snapchat, while staying close enough to the original to still ride whatever
made it buzz.

Deliberately NOT format18's white-card recomposition (modules.assembler.
white_card_reaction) -- the user was asked directly and chose to KEEP the
clip's own native framing/aesthetic instead of recomposing it onto a white
card with a black frame. For a single continuous clip (a moment/reaction/
scene, the normal case), what this module adds on top of the untouched
footage is:
  1. one short reframing caption, generated by Claude from the actual
     footage (never a canned template line) and burned on as a translucent-
     backed overlay near the top -- unlike format18 there's no guaranteed
     plain background to sit on, so the overlay carries its own backing bar.
  2. the same anti-duplication technical pass format18 already uses in
     production (modules.assembler.uniqueness), run on the WHOLE frame
     (box=None -- there's no static template to protect here, the entire
     frame is real footage).

TWO DIFFERENT KINDS OF "reused content" (2026-08-13, real user catch):
pixel/audio fingerprint matching (file hash, perceptual video hash, audio
fingerprint -- what the technical pass above defeats) is not the same as
content-SUBSTANCE matching (OCR on burned-in text, speech transcription,
plain "this is the same list of facts/conversation/scenario" recognition). A
source built around a NARRATIVE DEVICE -- not just a ranking/countdown, but
any structured format this pipeline itself already knows how to build from a
plain subject (a fake text-message thread, a two-voice dialogue/debate, a
quote card, a duel/vs framing, a dramatized phone-call scenario, a
choice/dilemma, a character read/audit, text-only motion graphics
contrasting two ideas...) -- fails on the second axis no matter how much the
pixels get tweaked: the on-screen text/dialogue/wording would still read as
the same content. 2026-08-13, second real user catch: this is NOT special to
ranking specifically -- EVERY structural format this pipeline can build from
a bare subject (see pipeline.py's dispatch, the "no clip_path, no external
voice recording, no RSS dependency" bucket) has the exact same problem, and
_analyze_source_clip/_ARCHETYPE_FORMATS below cover that whole set, not just
ranking.

_analyze_source_clip judges the source's STRUCTURE first (frames AND a
Whisper transcript of its audio -- several of these archetypes are far more
legible from spoken words than from silent frames, e.g. a dialogue/debate or
a dramatized phone call has little distinctive VISUAL signature but is
obvious the moment you can read what's being said). A recognized archetype
routes to a completely different branch that does NOT reuse the source's
footage/audio at all -- it extracts a fresh SUBJECT LINE (same general
topic, not the specific items/dialogue/wording) and hands it to the active
BRAND'S OWN format for that archetype (_regen_format_for_brand /
_ARCHETYPE_FORMATS -- ResetWorth's "format6" vs MindFile's "mf3" for a
ranking, MindFile's "mf5" for a dialogue (ResetWorth has no dialogue format
actually in real use -- format11 exists in code but was never published,
see _ARCHETYPE_FORMATS), etc.), producing a wholly new
video: fresh script, fresh wording, fresh B-roll, in that brand's own voice,
on the same theme so it still rides the same wave of interest. Deliberately
NOT every format in the catalog -- excluded on purpose:
  - format1/format7/format18 -- clip-EDIT formats, need an external clip as
    their actual core input, not a plain subject (format18 is this module's
    own sibling for the single-clip case anyway)
  - format17 -- its content is real RSS news headlines (modules.news_fetcher),
    not led by an arbitrary subject string the way the others are
  - long1/long2/long3/mf_long -- long-form (real-voice-only or multi-minute
    renders), doesn't fit a quick short-form remix
  - format14 -- kept UI-hidden project-wide (config.py), not offered here
An archetype with NO format available for the active brand (e.g. MindFile
has no "audit"/"duel"/"dilemma" equivalent) falls all the way through to the
single-clip pixel-remix path below rather than forcing an off-niche format
on a mismatched brand -- e.g. routing a MindFile source through ResetWorth's
finance-flavored "audit" format would produce content that doesn't fit
MindFile's psychology niche at all, worse than just keeping the footage. A
source matching no recognized archetype at all keeps going through the
pixel-remix path too -- the normal case for a genuine single continuous
clip/moment/reaction with no narrative device layered on top.

Brand-agnostic and format-agnostic by design (user ask: every brand, not
tied to any one format's visual style) -- the single-clip branch's result is
a plain finished mp4 that drops straight into the existing Publication
panel's upload flow (app.py's /api/publish_upload / modules.publish.
upload_meta), exactly like any hand-uploaded video; the ranking branch's
result is a normal pipeline-generated video (modules.users.run_generator),
tagged/relocated to the active brand like any other generated video. Neither
branch publishes anything itself.

THIRD kind of "reused content" (2026-08-14, real user catch): everything
above (apply_uniqueness_pass's mirror/zoom/grain/crop/pitch-shift) only
defeats generic duplicate-content matching -- file hash, perceptual video
hash, audio waveform correlation. A source clip that is itself an excerpt
from a copyrighted movie/TV show/other professional production (recognizable
actors, VFX, film-set production values -- confirmed live against a Marvel
scene) is a completely different problem: rights-holder fingerprint matching
is far more robust than generic repost detection, runs mostly off the
original studio audio, and no amount of imperceptible pixel/audio tweaking
is going to defeat it. _analyze_source_clip's `is_licensed_media` flag
catches this (vision judgment: does the footage look like a professional
production vs personal/amateur/user-generated content).

2026-08-14 first attempt, REVERTED 2026-08-15 (explicit user correction):
is_licensed_media used to route to _build_broll_substitute, swapping the
source's footage/audio out entirely for mood-matched B-roll + music. That's
the wrong fix for what the user actually wants -- the whole point of
remixing an already-viral clip is riding ITS buzz: "changer assez pour que
ça soit pas répertorié comme reused content mais pas trop pour que ça reste
à peu près la même chose de sorte que je puisse resurfer sur le buzz". A
full swap changes FAR more than "pas trop". _build_broll_substitute stays
defined below (unwired) in case a future explicit opt-in wants it -- it is
NOT called by remix_from_source anymore. Instead, is_licensed_media now
just pushes apply_uniqueness_pass to its "strong" tier (see uniqueness.py's
_STRENGTH_RANGES) on the REAL source footage -- still recognizably the same
clip, transformed harder than the imperceptible default. This is a real
increase in how much gets perturbed, NOT a guaranteed bypass of a
rights-holder's own fingerprint matching -- that ceiling (see above) doesn't
change just because the knobs turn further.
"""

