def _analyze_source_clip(video_path: str, brand_voice: str, angle_hint: str | None) -> dict:
    """
    Looks at the actual footage (+ a transcript of its audio, see
    _transcribe_source) and returns {"archetype": str, "subject": str,
    "caption": str, "has_onscreen_text": bool, "text_zone": str,
    "is_licensed_media": bool, "quote_original": str}.

    archetype picks which branch remix_from_source takes -- one of
    _ARCHETYPE_FORMATS's keys, or "none" -- see this module's docstring for
    why pixel-level tweaks alone aren't enough for any of these structured
    archetypes, not just ranking (2026-08-13, real user catch: "y'a pas que
    visuel, faudrait que le fond aussi soit proche mais pas identique", then
    a second catch the same day: "pas que les formats ranking... VRAIMENT
    tous"). subject AND caption are ALWAYS both filled in regardless of
    archetype (2026-08-13, real quality bug caught in testing: remix_from_
    source used to fall back to the SUBJECT line as the on-screen caption
    whenever a detected archetype had no format for the active brand -- a
    subject line reads like a clinical topic label, not an actual caption a
    human would post, e.g. "money psychology dilemma: hoarding wealth for
    safety versus..." -- asking for a real caption every time, unused when
    archetype != "none" AND the brand DOES own that archetype's format,
    costs nothing extra since it's the same single call either way).

    `angle_hint` optionally steers either outcome without dictating exact
    wording, same convention as format18's `idea` param -- EXCEPT an
    explicit verbatim trigger (_extract_verbatim_caption, shared with
    format18), which short-circuits straight to the single-clip caption
    branch (archetype "none") with the hint's own text rendered unchanged
    (verbatim means "use THIS clip with THIS exact caption", never a
    from-scratch regen).

    has_onscreen_text: Claude's own read of whether the sampled frames show
    ANY readable burned-in text already baked into the source clip -- NOT a
    logo/watermark alone. The verbatim path makes no vision call, so it
    can't check -- defaults to True (assume text present, skip mirroring)
    to stay on the conservative side rather than silently risk it.

    text_zone: "top" | "bottom" | "center" | "spread" | "none" -- roughly
    where that existing text sits, so _render_caption_overlay can place OUR
    caption somewhere else. 2026-08-13, real bug caught in live testing: a
    source clip that already had its own text at the top collided directly
    with our overlay when both always landed at the same top position,
    producing two illegible stacked text blocks. Defaults to "top" (the
    single most common placement for reposted captions) when missing/
    malformed or on the verbatim path -- conservative, pushes our own
    caption to the bottom zone rather than risk a collision.

    is_licensed_media: Claude's own read of whether the footage looks like
    an excerpt from a copyrighted movie/TV/professional production rather
    than personal/amateur/user-generated content -- see this module's
    docstring's "THIRD kind of reused content" section for why this needs a
    completely different fix (B-roll substitution) than the other two.
    Defaults to False (not conservative-True) when missing/malformed, and on
    the verbatim path. Only consulted by the caller when archetype == "none"
    -- a recognized archetype already regenerates from scratch and never
    reuses the source footage anyway, so the flag would be moot there.

    quote_original: 2026-08-17, real user catch -- the "quote" archetype used
    to throw the source's actual wording away entirely, keeping only the
    generic `subject` topic line, then handed that bare topic to the brand's
    own quote format (format3/mf2) whose own script generator invents a
    completely fresh line in its own house voice (format3's is even forced
    into a specific violent/mortality-stakes register) -- the result read as
    unrelated to what the original clip actually said, not "the same thing,
    worded differently" ("j'étais pas fan de ce que tu faisais... tu vas
    juste changer la quote... un truc qui est à peu près la même chose mais
    qui n'est pas dit exactement de la même manière"). This field is Claude's
    best verbatim read of the actual quote/statement text, kept separate from
    `subject` on purpose -- see remix_from_source's use of
    _paraphrase_quote_text, which rewords THIS text instead of the format's
    own script generator inventing an unrelated one from the topic alone.
    Empty string for every other archetype, and on the verbatim path (no
    vision call made there).
    """
    verbatim = _extract_verbatim_caption(angle_hint) if angle_hint else None
    if verbatim:
        logger.info(f"viral_remix: verbatim caption requested -> {verbatim!r}")
        # is_licensed_media=False here on purpose -- verbatim means the user
        # explicitly asked to keep THIS footage as-is, overriding the usual
        # judgment call the same way it already overrides archetype
        # detection (forced to "none" above).
        return {"archetype": "none", "subject": "", "caption": verbatim,
                "has_onscreen_text": True, "text_zone": "top", "is_licensed_media": False,
                "quote_original": ""}

    frames = _extract_preview_frames(video_path)
    if not frames:
        raise RuntimeError("viral_remix: could not extract any preview frames from the source clip")

    try:
        transcript = _transcribe_source(video_path)
        transcript_line = (
            f'\n\nTranscript of the clip\'s spoken audio: "{transcript}"' if transcript else
            "\n\nNo speech detected in the clip's audio (silent, music-only, or transcription "
            "unavailable) -- judge by the visuals alone."
        )
        angle_line = (
            f'\nThe user wants the result steered by this idea/angle: "{angle_hint}"' if angle_hint else
            "\nNo specific angle was given -- invent whatever framing best matches what's actually "
            "happening in the clip."
        )
        prompt = (
            "\n".join(f"@{f}" for f in frames)
            + "\n\nOpen and actually look at EVERY one of the image files referenced above before "
              "answering anything below -- do not answer from the filenames, from general familiarity "
              "with this project/codebase, or from a guess at what a typical clip like this usually "
              "contains. Base every field strictly on what these specific frames actually show."
            + "\n\nThese frames are sampled evenly across one short clip that already went viral "
              "elsewhere: mood, body language, props, the arc from the first frame to the last."
            + transcript_line
            + angle_line
            + f"\n\nWrite the caption in the voice of {brand_voice}.\n\n"
              'Return JSON only: {"archetype": "<one of ranking / chat / quote / dialogue / dilemma / '
              'audit / duel / hotline / motion_pov / none>", '
              '"subject": "<topic line -- ALWAYS filled in, regardless of archetype>", '
              '"caption": "<max 8 words caption, PLAIN TEXT with no quote marks of your own -- ALWAYS '
              'filled in, regardless of archetype>", '
              '"has_onscreen_text": <bool, true if these frames show ANY readable burned-in text -- '
              'captions, subtitles, bold on-screen words, UI text -- false if it is just plain footage '
              'with at most a small logo/watermark and no readable words>, '
              '"text_zone": "<one of top / bottom / center / spread / none -- where that existing text '
              'sits, only meaningful when has_onscreen_text is true>", '
              '"is_licensed_media": <bool, true if this footage looks like an excerpt from a copyrighted '
              'movie, TV show, or other professional/studio production -- recognizable actors or '
              'characters, VFX, film-set cinematography and production values -- false for personal/'
              'amateur/user-generated footage (a phone recording, livestream, reaction, skit, vlog) even '
              'if it is well-shot or well-edited>, '
              '"quote_original": "<ONLY when archetype is quote: the literal quote/statement text, '
              'word for word as shown or said -- empty string for every other archetype>"'
              '}'
        )
        from modules.claude_cli import call_claude
        raw, _, _ = call_claude(_ANALYSIS_SYSTEM_PROMPT, prompt, model=CLAUDE_MODEL, timeout=90)
        raw = raw.strip()
        m = re.search(r"\{.*\}", raw, re.S)
        if not m:
            raise RuntimeError(f"viral_remix: no JSON in Claude's response: {raw[:200]!r}")
        parsed = json.loads(m.group(0))

        archetype = str(parsed.get("archetype", "none")).strip().lower() or "none"
        if archetype not in _ARCHETYPE_FORMATS and archetype != "none":
            logger.warning(f"viral_remix: unknown archetype {archetype!r} from Claude, treating as 'none'")
            archetype = "none"
        subject = str(parsed.get("subject", "")).strip()
        caption = str(parsed.get("caption", "")).strip().strip("\"'“”‘’").strip()
        # Conservative defaults if fields are missing/malformed: assume text
        # present (skip mirroring) at the top (push our own caption to the
        # bottom zone instead of risking a collision).
        has_onscreen_text = bool(parsed.get("has_onscreen_text", True))
        text_zone = str(parsed.get("text_zone", "top")).strip().lower() or "top"
        if text_zone not in ("top", "bottom", "center", "spread", "none"):
            text_zone = "top"
        # Default False (not conservative-True like has_onscreen_text) --
        # the failure mode of wrongly assuming "amateur footage" is just the
        # ordinary pixel-remix path (already a reasonable outcome), while
        # wrongly assuming "licensed" on every clip would make the B-roll
        # substitution fire needlessly and throw away good original footage.
        is_licensed_media = bool(parsed.get("is_licensed_media", False))
        # Only meaningful when archetype == "quote" (see _paraphrase_quote_text
        # / remix_from_source) -- the literal original wording, kept SEPARATE
        # from `subject` (a topic line, deliberately stripped of exact
        # wording) precisely because the "quote" archetype needs the exact
        # wording as a starting point to paraphrase FROM, not just a theme.
        quote_original = str(parsed.get("quote_original", "")).strip().strip("\"'“”‘’").strip()

        if not subject:
            raise RuntimeError("viral_remix: Claude returned no subject line")
        if not caption:
            raise RuntimeError("viral_remix: Claude returned an empty caption")

        logger.info(f"viral_remix: source analyzed | archetype={archetype} | subject={subject!r} "
                    f"| caption={caption!r} | has_onscreen_text={has_onscreen_text} | text_zone={text_zone} "
                    f"| is_licensed_media={is_licensed_media} | quote_original={quote_original!r}")
        return {"archetype": archetype, "subject": subject, "caption": caption,
                "has_onscreen_text": has_onscreen_text, "text_zone": text_zone,
                "is_licensed_media": is_licensed_media, "quote_original": quote_original}
    finally:
        for f in frames:
            f.unlink(missing_ok=True)


def _render_caption_overlay(text: str, frame_w: int, frame_h: int, zone: str = "top") -> Path:
    """
    Full-frame transparent PNG with `text` drawn white on a translucent dark
    backing bar (rounded rect) -- unlike format18's white card there's no
    guaranteed plain background here, so legibility comes from the bar
    itself rather than from the underlying footage. Sized as fractions of
    frame_w/frame_h so it scales to whatever resolution the source clip
    actually is.

    zone: "top" (default) or "bottom" -- which safe area to place the text
    in. remix_from_source picks "bottom" when the source clip's own footage
    already carries burned-in text near the top (see _analyze_source_clip's
    text_zone) -- 2026-08-13, real bug caught in live testing: both landing
    at the same top position produced two illegible stacked text blocks.
    """
    overlay = Image.new("RGBA", (frame_w, frame_h), (0, 0, 0, 0))
    draw = ImageDraw.Draw(overlay)

    side_margin = round(frame_w * _SIDE_MARGIN_FRAC)
    safe_width  = frame_w - 2 * side_margin
    max_size    = round(frame_w * _TEXT_MAX_SIZE_FRAC)
    min_size    = round(frame_w * _TEXT_MIN_SIZE_FRAC)
    bar_pad     = round(frame_w * _BAR_PAD_FRAC)

    size = max_size
    while size >= min_size:
        font = ImageFont.truetype(_FONT_BOLD_PATH, size=size)
        char_w = max(1, draw.textbbox((0, 0), "M", font=font)[2])
        wrap_width = max(3, int(safe_width / (char_w * 0.58)))
        wrapped = _wrap_preserving_breaks(text, wrap_width)
        bbox = draw.multiline_textbbox((0, 0), wrapped, font=font, align="center", spacing=8)
        if bbox[2] - bbox[0] <= safe_width:
            break
        size -= 4
    else:
        size = min_size
        font = ImageFont.truetype(_FONT_BOLD_PATH, size=size)
        wrapped = _wrap_preserving_breaks(text, max(3, int(safe_width / (size * 0.5))))
        bbox = draw.multiline_textbbox((0, 0), wrapped, font=font, align="center", spacing=8)

    text_w = bbox[2] - bbox[0]
    text_h = bbox[3] - bbox[1]
    top_y  = round(frame_h * (_BOTTOM_Y_FRAC if zone == "bottom" else _TOP_Y_FRAC))
    cx     = frame_w // 2

    bar_box = [
        cx - text_w // 2 - bar_pad, top_y - bar_pad,
        cx + text_w // 2 + bar_pad, top_y + text_h + bar_pad,
    ]
    radius = round(bar_pad * 1.4)
    draw.rounded_rectangle(bar_box, radius=radius, fill=(10, 10, 10, 160))
    draw.multiline_text((cx - text_w // 2, top_y - bbox[1]), wrapped, font=font,
                         fill=(255, 255, 255, 255), align="center", spacing=8)

    tmp = Path(tempfile.gettempdir()) / "vid_pipeline_viral_remix"
    tmp.mkdir(exist_ok=True)
    out = tmp / "caption_overlay.png"
    overlay.save(str(out), "PNG")
    return out


def _build_broll_substitute(subject: str, duration: float, w: int, h: int) -> Path | None:
    """
    NOT CURRENTLY CALLED (2026-08-15) -- remix_from_source stopped wiring
    this in after an explicit user correction: is_licensed_media swapping
    the footage out entirely changes far more than the user actually wants
    for a clip they're deliberately trying to keep riding the buzz of (see
    this module's docstring's "THIRD kind of reused content" section for the
    full story). Left defined, working, and unit-tested-in-practice (it DID
    run successfully end to end once, 2026-08-14) in case a future explicit
    opt-in wants a full-swap mode -- if reviving this, wire it behind its own
    flag, not back onto is_licensed_media directly.

    Replaces a source clip's own footage AND audio with a montage of
    generic mood-matched B-roll from the project's curated pool (modules.
    clips.clip_broll -- the same pool format1's cutaway bursts pull from),
    covering the clip's FULL duration rather than just a burst window, plus
    a matched music bed (modules.music.music_library, the same selector
    every other format uses). Only called when _analyze_source_clip flags
    the source as `is_licensed_media` (see this module's docstring's "THIRD
    kind of reused content" section) -- apply_uniqueness_pass's pixel-level
    transforms only defeat generic duplicate-content matching, never a
    rights-holder's own fingerprint of actual movie/TV footage, so the only
    real fix for THAT case is not reusing the footage (or its audio) at all.
    The caller still adds the caption on top afterward -- this function only
    replaces what's underneath it.

    Returns None (caller falls back to the ordinary pixel-remix path on the
    real source footage -- fails soft, same convention as
    apply_uniqueness_pass) if the curated B-roll pool has nothing usable for
    these keywords.
    """
    import math
    from modules.clips.clip_broll import extract_broll_keywords, fetch_broll_clips
    from modules.music.music_library import select_music

    keywords = extract_broll_keywords(subject, n=6)
    n_segments = max(1, math.ceil(duration / _BROLL_SEGMENT_DUR))

    _BROLL_TMP_DIR.mkdir(parents=True, exist_ok=True)
    for f in _BROLL_TMP_DIR.glob("*"):
        f.unlink(missing_ok=True)

    clips = fetch_broll_clips(keywords, n_segments, _BROLL_TMP_DIR, full_text=subject)
    if not clips:
        logger.warning("viral_remix: is_licensed_media fired but no B-roll available -- "
                        "falling back to the source clip's own footage")
        return None
    # fetch_broll_clips may return fewer usable clips than requested (small
    # pool) -- cycle through what it did return rather than truncating the
    # montage short of the source's actual duration.
    picks = [clips[i % len(clips)] for i in range(n_segments)]

    filters = []
    for i in range(n_segments):
        filters.append(
            f"[{i}:v]scale={w}:{h}:force_original_aspect_ratio=increase,"
            f"crop={w}:{h},setsar=1,fps=30,trim=0:{_BROLL_SEGMENT_DUR:.3f},"
            f"setpts=PTS-STARTPTS[seg{i}]"
        )
    concat_labels = "".join(f"[seg{i}]" for i in range(n_segments))
    filters.append(f"{concat_labels}concat=n={n_segments}:v=1:a=0[vcat]")
    filters.append(f"[vcat]trim=0:{duration:.3f},setpts=PTS-STARTPTS[vout]")

    cmd = ["ffmpeg", "-y"]
    for p in picks:
        cmd += ["-i", str(p)]

    music_path = select_music({"subject": subject})
    music_idx = None
    if music_path:
        cmd += ["-stream_loop", "-1", "-i", str(music_path)]
        music_idx = n_segments
        filters.append(f"[{music_idx}:a]atrim=0:{duration:.3f},asetpts=PTS-STARTPTS,volume=0.5[aout]")

    cmd += ["-filter_complex", ";".join(filters), "-map", "[vout]"]
    if music_idx is not None:
        cmd += ["-map", "[aout]", "-c:a", "aac", "-b:a", "192k"]
    out = _BROLL_TMP_DIR / "broll_substitute.mp4"
    cmd += ["-c:v", "libx264", "-preset", "fast", "-crf", "19", "-pix_fmt", "yuv420p", str(out)]
    _run_ffmpeg(cmd)

    logger.info(f"viral_remix: built B-roll substitute ({n_segments} clip(s), keywords={keywords}) "
                f"-> {out} | music={'yes' if music_idx is not None else 'no'}")
    return out


_PARAPHRASE_SYSTEM_PROMPT = (
    "You reword a single short quote or statement so it lands as the SAME message, said a different "
    "way -- close in meaning and tone to the original, but not the same sentence. Not a synonym-swap "
    "word puzzle, not a watered-down summary -- write it the way a different person would naturally "
    "say the same thing. Keep it roughly the same length and register (casual stays casual, blunt "
    "stays blunt). Same language as the original. Direct. No em dashes, no quotation marks, no "
    "explanation -- output ONLY the reworded line itself."
)


def _paraphrase_quote_text(original: str) -> str:
    """
    2026-08-17, real user ask: the "quote" archetype (see _ARCHETYPE_FORMATS)
    used to hand the brand's own quote format (format3/mf2) nothing but a
    generic topic line, so that format's own script generator invented an
    entirely unrelated line in its own house voice (format3's is even forced
    into a specific violent/mortality-stakes register by design, see
    modules.script_generator's FORMATS["format3"]) -- the result didn't read
    as "the same thing, worded differently", it read as a different quote
    altogether. This rewords the SOURCE clip's own actual wording instead --
    same message, different words -- so remix_from_source can force it onto
    the render as that format's on-screen line (see `quote_override` on
    pipeline.run) instead of letting the script generator invent one from
    scratch.

    Deliberately does NOT apply the active brand's own voice/niche framing
    here (unlike _brand_voice_line's use elsewhere in this module) -- the
    whole point is fidelity to what the original quote actually said, not a
    ResetWorth/MindFile-flavored rewrite of it.

    Raises RuntimeError on any call/parse failure (empty/whitespace response)
    -- same "fail loud, don't silently downgrade" convention as
    generate_joke_lines; the caller has no sane fallback quote to use instead
    of a bad one.
    """
    prompt = (
        f'Original quote: "{original}"\n\n'
        "Reword it now, same rules as above."
    )
    from modules.claude_cli import call_claude
    raw, _, _ = call_claude(_PARAPHRASE_SYSTEM_PROMPT, prompt, model=CLAUDE_MODEL, timeout=60)
    reworded = raw.strip().strip("\"'“”‘’").strip()
    if not reworded:
        raise RuntimeError("viral_remix: paraphrase call returned an empty line")
    logger.info(f"viral_remix: quote paraphrased | original={original!r} -> reworded={reworded!r}")
    return reworded


_PARAPHRASE_OPTIONS_SYSTEM_PROMPT = (
    "You reword a single short quote or statement several DIFFERENT ways, each keeping the SAME "
    "message and the SAME specific comedic/rhetorical device as the original -- close in meaning and "
    "tone, but not the same sentence, and not each other's synonym-swap twin either (each option "
    "should feel like a genuinely different way of saying it, not a word or two changed). Not a "
    "watered-down summary -- if the original's punchline hinges on one specific word/twist (e.g. who "
    "says \"we\" about something they didn't do), EVERY option must preserve that exact twist, not "
    "drift into a different angle (e.g. don't turn a pronoun-hijack joke into a joke about money/effort "
    "instead). Keep each option roughly the same length and register as the original (casual stays "
    "casual, blunt stays blunt). Same language as the original. Direct. No em dashes, no quotation "
    "marks around each line, no numbering, no explanation."
)


def propose_quote_paraphrases(original: str, n: int = 4) -> list[str]:
    """
    2026-08-17, real user ask: rather than silently auto-picking ONE
    paraphrase (_paraphrase_quote_text) and building straight from it, the
    "quote" archetype now offers the user `n` distinct reworded options to
    choose from first -- see app.py's /api/remix_source (propose step) +
    /api/remix_source/finalize (build step) for the two-phase flow this
    feeds. One call asking for all `n` at once (not `n` separate calls to
    _paraphrase_quote_text) so the options are explicitly steered to differ
    from EACH OTHER, not just from the original -- confirmed live during
    manual testing that a naive reword can drift off the original's specific
    comedic device (e.g. "WE got a Lamborghini" hinges on the pronoun, not on
    money/effort) if the prompt only says "keep the same meaning" without
    also saying "keep the same device".

    Raises RuntimeError on any call/parse failure or if fewer than 2 usable
    lines come back -- same "fail loud" convention as _paraphrase_quote_text,
    the caller (a UI picker) has no sane single fallback to silently use
    instead of a short/broken list.
    """
    prompt = (
        f'Original quote: "{original}"\n\n'
        f"Give me {n} different reworded options, same rules as above.\n\n"
        f'Return JSON only: {{"options": ["<option 1>", "<option 2>", ...]}} -- exactly {n} strings.'
    )
    from modules.claude_cli import call_claude
    raw, _, _ = call_claude(_PARAPHRASE_OPTIONS_SYSTEM_PROMPT, prompt, model=CLAUDE_MODEL, timeout=60)
    raw = raw.strip()
    m = re.search(r"\{.*\}", raw, re.S)
    if not m:
        raise RuntimeError(f"viral_remix: no JSON in paraphrase-options response: {raw[:200]!r}")
    parsed = json.loads(m.group(0))
    options = [str(o).strip().strip("\"'“”‘’").strip() for o in parsed.get("options", [])]
    options = [o for o in options if o]
    if len(options) < 2:
        raise RuntimeError(f"viral_remix: paraphrase-options call returned too few usable lines: {options!r}")
    logger.info(f"viral_remix: {len(options)} quote paraphrase options | original={original!r} -> {options!r}")
    return options


def analyze_remix_source(ctx, source_path: Path, angle_hint: str | None = None) -> dict:
    """
    Phase 1 of the two-phase remix flow (2026-08-17, real user ask -- see
    build_remix_from_plan's docstring for why this got split out of what used
    to be one single `remix_from_source` call). Looks at the clip and decides
    EVERYTHING except the actual render -- returns a `plan` dict for
    build_remix_from_plan to execute, either immediately (most archetypes) or
    after the caller has shown the user quote options and collected a pick
    ("quote" archetype specifically, see `needs_quote_choice` below).

    _analyze_source_clip decides which of two very different paths the plan
    takes (2026-08-13, real user catch, then a second one the same day --
    see this module's docstring for why EVERY structured archetype this
    pipeline can build from a bare subject needs its CONTENT changed, not
    just its pixels, not only ranking):

    - recognized archetype (ranking, dialogue, chat, quote, dilemma, audit,
      duel, hotline, motion_pov) with a format the active brand actually
      owns -> plan["kind"] = "regen": a BRAND NEW video from scratch via that
      brand's own format for it (_regen_format_for_brand -- modules.users.
      run_generator), on the same general topic but with its own fresh
      script/wording/items/B-roll, in that brand's own voice. The source
      clip's footage/audio is never reused. An archetype the active brand has
      NO format for (_regen_format_for_brand returns None) falls through to
      the pixel-remix plan below instead of forcing an off-niche format.
      EXCEPTION, "quote" specifically (2026-08-17, real user ask): the
      on-screen line itself is NOT left to that format's own from-scratch
      invention -- plan["needs_quote_choice"] is True and plan["quote_original"]
      carries the source clip's own actual wording, for the caller to turn
      into a few reworded options (propose_quote_paraphrases) and let the
      user pick one before build_remix_from_plan runs -- same message worded
      differently, rather than an unrelated line the format's script
      generator would otherwise invent from just a topic. Everything else
      about the regen (B-roll, assembler, body/cta/description) is unchanged.

    - single continuous clip -> plan["kind"] = "pixel_remix": a short
      reframing caption overlay + the same anti-duplication technical pass
      format18 uses, applied directly to the source footage (see
      build_remix_from_plan for the render itself).
    """
    dur = _duration_ffprobe(str(source_path))
    if dur > 180:
        logger.warning(f"viral_remix: source clip is {dur:.0f}s, unusually long for a short-form remix "
                        f"-- proceeding untrimmed anyway")

    brand_voice = _brand_voice_line(ctx)
    analysis = _analyze_source_clip(str(source_path), brand_voice, angle_hint)

    regen_fmt = _regen_format_for_brand(ctx, analysis["archetype"]) if analysis["archetype"] != "none" else None
    if regen_fmt:
        needs_quote_choice = bool(analysis["archetype"] == "quote" and analysis.get("quote_original"))
        logger.info(f"viral_remix: source is archetype={analysis['archetype']!r} -> will regenerate from "
                    f"scratch via {regen_fmt} ({ctx.name}), subject={analysis['subject']!r} "
                    f"(source footage/audio not reused)"
                    + (" | needs quote choice" if needs_quote_choice else ""))
        return {
            "kind": "regen", "regen_fmt": regen_fmt, "subject": analysis["subject"],
            "archetype": analysis["archetype"], "needs_quote_choice": needs_quote_choice,
            "quote_original": analysis.get("quote_original", ""),
        }
    if analysis["archetype"] != "none":
        logger.info(f"viral_remix: source is archetype={analysis['archetype']!r} but brand {ctx.name!r} "
                    f"has no matching format -- falling back to the single-clip pixel-remix path")

    # _analyze_source_clip always fills in a real caption regardless of
    # archetype (2026-08-13, real quality bug caught in testing: this used
    # to fall back to the SUBJECT line here when the brand had no matching
    # format for a detected archetype, which reads like a clinical topic
    # label -- "money psychology dilemma: hoarding wealth..." -- not an
    # actual on-screen caption a human would post) -- always usable as-is.
    return {
        "kind": "pixel_remix", "caption": analysis["caption"],
        "has_onscreen_text": analysis["has_onscreen_text"], "text_zone": analysis["text_zone"],
        "is_licensed_media": analysis.get("is_licensed_media", False), "needs_quote_choice": False,
    }


def build_remix_from_plan(ctx, source_path: Path, plan: dict, quote_choice: str | None = None) -> Path:
    """
    Phase 2 of the two-phase remix flow -- executes a plan already decided by
    analyze_remix_source. Split into two functions (2026-08-17, real user
    ask) so app.py can show the user a few reworded quote options
    (propose_quote_paraphrases) and let them PICK one before the actual video
    gets built, instead of silently auto-picking a single paraphrase like the
    original one-call `remix_from_source` did -- live testing during that
    build (an actual "WE got a Lamborghini" clip) showed paraphrase quality
    varies enough call to call that the user wants a say, not just a preview.

    `quote_choice`: only meaningful when plan["needs_quote_choice"] is True.
    The user's picked (or possibly hand-edited) reworded line, used AS-IS as
    the render's on-screen quote -- no further rewording. When
    needs_quote_choice is True but quote_choice is None (a caller that skips
    the picker UI, e.g. a script/test), falls back to auto-picking one
    paraphrase itself (_paraphrase_quote_text) so this function still works
    standalone -- the picker is a UI improvement layered on top, not a new
    hard requirement to call this at all.
    """
    if plan["kind"] == "regen":
        quote_override = None
        if plan.get("needs_quote_choice"):
            quote_override = (quote_choice or "").strip() or _paraphrase_quote_text(plan["quote_original"])
        from modules import users
        return users.run_generator(ctx, plan["regen_fmt"], plan["subject"], quote_override=quote_override)

    # plan["kind"] == "pixel_remix"
    w, h = _probe_dims(str(source_path))
    caption = plan["caption"]
    has_onscreen_text = plan["has_onscreen_text"]

    working_path = source_path
    # 2026-08-15, explicit user call: is_licensed_media does NOT swap the
    # footage out (_build_broll_substitute stays defined but unwired) --
    # the whole point of remixing an already-viral clip is riding ITS buzz,
    # "changer assez pour que ça soit pas répertorié comme reused content
    # mais pas trop pour que ça reste à peu près la même chose". Instead it
    # only pushes apply_uniqueness_pass to its "strong" tier on the real
    # footage -- still recognizably the same clip, just perturbed harder
    # than the imperceptible default. Neither tier is a guaranteed bypass of
    # a rights-holder's own fingerprint matching (see this module's
    # docstring's "THIRD kind of reused content" section) -- "strong" is a
    # real increase in how much gets changed, not a promise.
    strength = "strong" if plan.get("is_licensed_media") else "normal"

    # Existing text in (or spanning) the top zone pushes our own caption to
    # the bottom instead -- "center"/"spread"/"none"/unknown-top-adjacent
    # cases are treated as "top exists" too (conservative: prefer bottom
    # placement over risking a collision we didn't fully rule out).
    our_zone = "bottom" if (has_onscreen_text and plan["text_zone"] != "bottom") else "top"

    apply_uniqueness_pass(working_path, box=None, mirror=not has_onscreen_text, strength=strength)

    overlay_png = _render_caption_overlay(caption, w, h, zone=our_zone)

    videos_dir = _VIDEOS_DIR if ctx.is_default else (ctx.root / "output" / "videos")
    videos_dir.mkdir(parents=True, exist_ok=True)
    ts = datetime.now().strftime("%Y%m%d_%H%M%S")
    slug = _slugify(caption)
    out = videos_dir / f"{ts}_remix_{slug}.mp4"

    has_audio = _has_audio(str(working_path))
    cmd = ["ffmpeg", "-y", "-i", str(working_path), "-i", str(overlay_png),
           "-filter_complex", "[0:v][1:v]overlay=0:0[vout]",
           "-map", "[vout]"]
    if has_audio:
        cmd += ["-map", "0:a", "-c:a", "aac", "-b:a", "192k"]
    cmd += ["-c:v", "libx264", "-preset", "fast", "-crf", "19", "-pix_fmt", "yuv420p",
            "-movflags", "+faststart", str(out)]
    _run_ffmpeg(cmd)

    size_mb = out.stat().st_size / (1024 * 1024)
    logger.info(f"viral_remix: remix ready: {out} ({size_mb:.1f} MB) | caption={caption!r} "
                f"| mirrored={not has_onscreen_text} | strength={strength}")
    return out


def remix_from_source(ctx, source_path: Path, angle_hint: str | None = None) -> Path:
    """
    One-call convenience wrapper: analyze_remix_source + build_remix_from_plan
    back to back, auto-picking a quote paraphrase itself when the "quote"
    archetype applies rather than pausing for a user pick. This is the
    pre-2026-08-17 behavior of this function, kept for any caller that wants
    the old one-shot shape (e.g. a script/test) -- app.py's actual /api/
    remix_source route calls the two phases separately instead, so it can
    show the user paraphrase options in between (see build_remix_from_plan's
    docstring).
    """
